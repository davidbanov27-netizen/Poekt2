namespace ITIncidentSystem.Enums;

/// <summary>
/// Статус на инцидента — описва жизнения цикъл на проблема.
/// При промяна на статус се записва ред в IncidentHistory.
/// </summary>
public enum IncidentStatus
{
    Open        = 1,  // Регистриран, чака назначаване
    InProgress  = 2,  // Назначен на техник, в процес на решаване
    Resolved    = 3,  // Решен от техника, чака потвърждение
    Closed      = 4,  // Затворен — потребителят е доволен
    Cancelled   = 5   // Отменен — дублиращ или невалиден инцидент
}
